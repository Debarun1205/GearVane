/**
 * The router playground.
 *
 * This runs the real classifier - the same TaskClassifier the CLI, the app,
 * and the VS Code extension use - in the visitor's browser. Nothing is sent
 * anywhere: the engine is dependency-free TypeScript, and there is no backend
 * here to send it to.
 *
 * What it does not do is run a model. It shows which tier GearVane would pick
 * and the signals behind that choice, which is the part worth demonstrating.
 * A page that actually executed a prompt would need an API key in the page,
 * and a token in browser JavaScript is a token shipped to every visitor.
 *
 * The engine arrives from engine.js, generated by tools/build-site-engine.mjs.
 * If that bundle ever goes stale, `--check` fails the build, so this cannot
 * quietly demonstrate decisions the app no longer makes.
 */

import { route } from './engine.js';

/** Prompts that show a different tier each, so the box is worth playing with. */
const EXAMPLES = [
  'Fix the typo in the second paragraph of README.md',
  'Add a paginated GET endpoint for user activity, wired to the existing router and tests',
  'Investigate an intermittent race condition between the cache writer and the flush timer',
];

const TIER_BLURB = {
  local: 'Small weights on your machine. Free, offline, fast.',
  mid: 'Bigger local weights for multi-file work. Still free.',
  frontier: 'The heaviest local weights. Still free, and slower to load.',
};

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

/** Build the score bars, which is where the reasoning actually shows. */
function renderScores(result, host) {
  const tiers = ['local', 'mid', 'frontier'];
  let peak = 0;
  for (const tier of tiers) peak = Math.max(peak, result.scores[tier] ?? 0);
  if (peak <= 0) return;

  for (const tier of tiers) {
    const score = result.scores[tier] ?? 0;
    const row = el('div', 'play-score');
    row.append(el('span', 'play-score-label', tier));

    const track = el('div', 'play-score-track');
    const fill = el('div', `play-score-fill play-score-${tier}`);
    // Width as a percentage of the strongest tier, so the bars compare
    // against each other rather than against an arbitrary maximum.
    fill.style.width = `${Math.round((score / peak) * 100)}%`;
    track.append(fill);
    row.append(track);

    row.append(el('span', 'play-score-value', score.toFixed(2)));
    host.append(row);
  }
}

function renderResult(result) {
  const out = document.getElementById('play-output');
  if (!out) return;
  out.textContent = '';

  const head = el('div', 'play-head');
  const badge = el('span', `play-tier play-tier-${result.tier}`, result.tier);
  const confidence = el('span', 'play-confidence', `${Math.round(result.confidence * 100)}% confident`);
  head.append(badge, confidence);
  out.append(head);

  const blurb = el('p', 'play-blurb', TIER_BLURB[result.tier] ?? '');
  out.append(blurb);

  const model = el('p', 'play-model');
  model.append('Would run ', el('code', null, result.model));
  out.append(model);

  const scores = el('div', 'play-scores');
  renderScores(result, scores);
  out.append(scores);

  if (result.reasons.length === 0) {
    out.append(el('p', 'play-reasons-empty', 'No strong signals, so the classifier used its default.'));
    return;
  }

  const list = el('ul', 'play-reasons');
  for (const reason of result.reasons) {
    list.append(el('li', null, reason));
  }
  out.append(list);
}

function currentInput() {
  const prompt = document.getElementById('play-prompt');
  const files = document.getElementById('play-files');
  return {
    prompt: prompt ? prompt.value.trim() : '',
    filesTouched: files && files.value.trim() ? files.value.split(/[\s,]+/).filter(Boolean) : [],
    errorLoops: 0,
    testFailures: 0,
  };
}

function decide() {
  const input = currentInput();
  const out = document.getElementById('play-output');
  if (!input.prompt) {
    if (out) {
      out.textContent = '';
      out.append(el('p', 'play-reasons-empty', 'Type a task to see how it routes.'));
    }
    return;
  }
  // Synchronous by design: the engine has no I/O, so a spinner would be a lie
  // about work being done.
  renderResult(route(input));
}

function wire() {
  const prompt = document.getElementById('play-prompt');
  const files = document.getElementById('play-files');
  const run = document.getElementById('play-run');
  if (!prompt || !files || !run) return;

  run.addEventListener('click', decide);
  // Live as you type: the point is to see the reasoning move, which is lost
  // behind a button press.
  prompt.addEventListener('input', decide);
  files.addEventListener('input', decide);

  const examples = document.getElementById('play-examples');
  if (examples) {
    for (const text of EXAMPLES) {
      const button = el('button', 'play-example', text);
      button.type = 'button';
      button.addEventListener('click', () => {
        prompt.value = text;
        decide();
      });
      examples.append(button);
    }
  }

  decide();
}

if (typeof document !== 'undefined') {
  wire();
}